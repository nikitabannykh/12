/**
 * Слой группы поиска. «service» — запросы по самой услуге (основное ядро выше). Остальные три — расширение:
 *  - problem: тёплые запросы о проблеме или ситуации («болит шея», «ломкие ногти») — человек ещё не знает, какая услуга ему нужна;
 *  - adjacent: смежные специалисты и методы («мануальный терапевт», «хиропрактик») — без брендов конкурентов;
 *  - audience: услуга + аудитория или ситуация («остеопат для беременных», «маникюр на свадьбу»).
 * Группу слоя создаём, только если у владельца есть услуга, к которой ведёт запрос (to), — услуг, которых нет, не обещаем.
 */
